def tr(key: str, language: str) -> str:
    """Return the label for key under language, falling back to English."""
    table = STRINGS.get(language) or STRINGS[FALLBACK_LANGUAGE]
    return table.get(key, key)


class Translator:
    """Hold the active UI language and resolve string keys."""

    def __init__(self, language: str = DEFAULT_LANGUAGE) -> None:
        self._language = language

    @property
    def language(self) -> str:
        return self._language

    def set_language(self, language: str) -> None:
        """Switch the active language code."""
        self._language = language

    def tr(self, key: str) -> str:
        """Return the label for key in the active language."""
        return tr(key, self._language)
